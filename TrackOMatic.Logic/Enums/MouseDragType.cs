namespace TrackOMatic.Logic.Enums;

/// <summary>
/// Represents the type of mouse drag operation.
/// </summary>
public enum MouseDragType
{
    /// <summary>
    /// No mouse drag operation is occurring.
    /// </summary>
    None = 0,
    /// <summary>
    /// The left mouse button is used for the drag operation.
    /// </summary>
    Left,
    /// <summary>
    /// The right mouse button is used for the drag operation.
    /// </summary>
    Right
}
